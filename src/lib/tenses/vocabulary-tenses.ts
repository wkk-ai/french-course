/** Words used in the Grammar (tenses) pages that the main dictionary did not have. Ids 40000000-…. */
function v(
  n: number,
  word: string,
  meaning: string,
  part_of_speech: string,
  gender: 'masculine' | 'feminine' | null,
  french: string,
  english: string,
): VocabularyWord {
  return {
    id: `40000000-0000-0000-0000-${String(n).padStart(12, '0')}`,
    word,
    base_translation: meaning,
    meanings: meaning.split(';').map((m) => m.trim()),
    example: { french, english },
    part_of_speech,
    gender,
    register: 'Courant',
    ipa_pronunciation: null,
    is_idiom: part_of_speech === 'phrase',
    is_slang: false,
    idiom_explanation: null,
  }
}

