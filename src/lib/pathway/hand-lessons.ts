function pack(
  id: string,
  briefTitle: string,
  briefBody: string,
  reading: string[],
  setting: string,
  lines: Array<[string, string]>,
): LessonContent {
  const prefix = `hand-${id.slice(-4)}`
  return {
    brief: { title: briefTitle, body: bulletizeTheory(briefBody), ruleSlugs: SLUGS },
    reading: readingParagraphs(prefix, reading, V),
    conversation: {
      title: setting.split('.')[0] ?? setting,
      setting,
      lines: lines.map(([speaker, text], index) => conversationLine(speaker, text, `${prefix}-l${index}`, V)),
    },
    exercises: drills(prefix),
  }
}

